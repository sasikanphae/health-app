export const machineById = (id) => MACHINES.find((m) => m.id === id);

// Any exercise id → a uniform description for the exercise screen.
export function exerciseInfo(id) {
  const m = machineById(id);
  if (m) return { kind: 'machine', ...m };
  if (HOME_EXERCISES[id]) return { kind: 'home', id, type: id === 'plank' ? 'hold' : 'strength', ...HOME_EXERCISES[id] };
  if (ROUTINES[id]) return { kind: 'routine', id, type: 'timed', muscles: { primary: [], secondary: [] }, ...ROUTINES[id] };
  if (ALTERNATIVES[id]) {
    const parent = MACHINES.find((x) => x.alternatives.includes(id));
    return { kind: 'alt', id, type: parent?.type === 'cardio' ? 'timed' : 'strength', parent: parent?.id, muscles: parent?.muscles, ...ALTERNATIVES[id] };
  }
  return null;
}
